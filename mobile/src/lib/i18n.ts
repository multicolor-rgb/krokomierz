export const dictionaries: Record<Lang, Record<I18nKey, string>> = { pl, en };

export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.pl[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

export function useT() {
  const lang = useAppStore((s) => s.settings.lang);
  return (key: I18nKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
